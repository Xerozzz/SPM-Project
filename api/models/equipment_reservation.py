"""A quantity of one equipment type committed to one event (SCRUM-53). ADR-0038.

Against a type rather than a catalogue entry, because a requirement asks for a kind of
thing (ADR-0024, ADR-0033) and stock is counted across every location (SCRUM-52).

The event's window is copied in when the reservation is made. A reservation is a
commitment made against a particular period; if the event later moves, whether that
commitment still stands is Event Change Management's decision, not something a join
should quietly change underneath it.
"""

import uuid
from datetime import UTC, datetime

from sqlalchemy import CheckConstraint, DateTime, ForeignKey, Index, Integer, String, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from core.database import Base


def _now() -> datetime:
    return datetime.now(UTC)


class EquipmentReservation(Base):
    """One act of reserving some of a requirement's quantity."""

    __tablename__ = "equipment_reservations"
    __table_args__ = (
        # Mirroring migration 0024, to state the invariants rather than to be
        # autogenerated from: Alembic does not compare CHECK constraints.
        CheckConstraint("quantity >= 1", name="equipment_reservations_quantity_positive"),
        CheckConstraint("starts_at < ends_at", name="equipment_reservations_window_ordered"),
        Index(
            "ix_equipment_reservations_live_type",
            "equipment_type",
            postgresql_where=text("released_at IS NULL"),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    requirement_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("event_equipment_requirements.id"),
        nullable=False,
        index=True,
    )
    # Kept beside the requirement so "what has this event reserved" and "what have other
    # events reserved" are read without joining through the requirement.
    event_request_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("event_requests.id"), nullable=False, index=True
    )
    equipment_type: Mapped[str] = mapped_column(String(200), nullable=False)
    quantity: Mapped[int] = mapped_column(Integer, nullable=False)
    # AC2: the event's date and time at the moment of reserving.
    starts_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    ends_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    created_by_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id"), nullable=False
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=_now
    )
    # Null means the reservation still holds stock. Nothing sets it yet: releasing belongs
    # to Event Change Management.
    released_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    # Reserved for the next story (a changed requirement flags its reservation rather than
    # releasing it, SCRUM-43 AC6). Unused here.
    flagged_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
