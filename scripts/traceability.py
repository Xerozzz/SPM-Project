#!/usr/bin/env python3
"""Generate a story -> test traceability matrix from pytest story markers.

Every test is tagged with the story it proves:

    @pytest.mark.story("US-14")
    def test_overlapping_booking_is_rejected(): ...

Register the marker in `pyproject.toml` so `--strict-markers` catches typos:

    [tool.pytest.ini_options]
    markers = ["story(id): the user story this test provides evidence for"]

Run from the `api/` directory:

    python ../scripts/traceability.py > traceability.md

This produces deliverable 3's traceability evidence from the tests themselves, so it cannot
drift out of date the way a hand-maintained spreadsheet does. CI regenerates it on every run
and uploads it as a build artifact. It also lists untagged tests, which is the signal that
somebody shipped a test without linking it to a story.
"""

from __future__ import annotations

import contextlib
import io
import os
import sys
from collections import defaultdict

import pytest


class _StoryCollector:
    """Pytest plugin that records the story markers on every collected test."""

    def __init__(self) -> None:
        self.items: list[tuple[str, list[str]]] = []

    def pytest_collection_modifyitems(self, items):  # noqa: D102 (pytest hook)
        for item in items:
            stories = [
                str(arg)
                for marker in item.iter_markers(name="story")
                for arg in marker.args
            ]
            self.items.append((item.nodeid, stories))


def collect(paths: list[str]) -> list[tuple[str, list[str]]]:
    """Collect tests without running them, capturing pytest's own chatter."""
    collector = _StoryCollector()
    args = ["--collect-only", "-q", "--no-header", "-p", "no:cacheprovider", *paths]
    sink = io.StringIO()
    with contextlib.redirect_stdout(sink), contextlib.redirect_stderr(sink):
        exit_code = pytest.main(args, plugins=[collector])
    # 0 = tests collected, 5 = none collected (an empty suite is not an error here).
    if exit_code not in (0, 5):
        sys.stderr.write(sink.getvalue())
        raise SystemExit(f"pytest collection failed with exit code {exit_code}")
    return collector.items


def kind(nodeid: str) -> str:
    """Classify a test by the directory it lives in."""
    path = nodeid.split("::", 1)[0]
    segments = {segment.lower() for segment in path.split(os.sep) if segment}
    segments |= {segment.lower() for segment in path.split("/") if segment}
    if "e2e" in segments:
        return "e2e"
    if "integration" in segments:
        return "integration"
    return "unit"


def story_sort_key(story: str) -> tuple[str, int]:
    prefix, _, number = story.rpartition("-")
    return (prefix, int(number)) if number.isdigit() else (story, 0)


def render(items: list[tuple[str, list[str]]]) -> str:
    by_story: dict[str, list[str]] = defaultdict(list)
    untagged: list[str] = []

    for nodeid, stories in items:
        if stories:
            for story in stories:
                by_story[story].append(nodeid)
        else:
            untagged.append(nodeid)

    out: list[str] = [
        "# Traceability matrix — user stories to tests",
        "",
        "Generated by `scripts/traceability.py` from `@pytest.mark.story` markers.",
        "Do not edit by hand.",
        "",
        f"Stories covered: **{len(by_story)}** · "
        f"Tagged tests: **{sum(len(v) for v in by_story.values())}** · "
        f"Untagged tests: **{len(untagged)}**",
        "",
        "| Story | Tests | Unit | Integration | E2E |",
        "|---|---:|---:|---:|---:|",
    ]

    for story in sorted(by_story, key=story_sort_key):
        kinds = [kind(nodeid) for nodeid in by_story[story]]
        out.append(
            f"| {story} | {len(kinds)} | {kinds.count('unit')} | "
            f"{kinds.count('integration')} | {kinds.count('e2e')} |"
        )

    out += ["", "## Detail", ""]
    for story in sorted(by_story, key=story_sort_key):
        out.append(f"### {story}")
        out.append("")
        out += [f"- `{nodeid}`" for nodeid in sorted(by_story[story])]
        out.append("")

    if untagged:
        out += [
            f"## Untagged tests ({len(untagged)})",
            "",
            "These prove no story. Tag them, or justify them at the next retrospective.",
            "",
        ]
        out += [f"- `{nodeid}`" for nodeid in sorted(untagged)]
        out.append("")

    return "\n".join(out)


def main() -> None:
    paths = sys.argv[1:] or ["tests"]
    print(render(collect(paths)))


if __name__ == "__main__":
    main()
